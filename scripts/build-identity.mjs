import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const hash = createHash('sha256');
function walk(root) { for (const e of readdirSync(root, { withFileTypes: true }).sort((a,b) => a.name.localeCompare(b.name))) { const file = path.join(root,e.name); if(e.isDirectory()) walk(file); else if (!file.endsWith('build-info.ts')) { hash.update(file.replaceAll('\\','/')); hash.update(readFileSync(file)); } } }
for (const root of ['src','hub','public','android/app/src/main/java','android/app/src/main/res','ios/App/App/Assets.xcassets','ios/App/App/Base.lproj','ios/App/App']) {
  if (root === 'ios/App/App') { for(const file of ['HomeDiscoveryPlugin.swift','Info.plist','PrivacyInfo.xcprivacy','DirectLan.entitlements']) hash.update(readFileSync(path.join(root,file))); }
  else walk(root);
}
hash.update(readFileSync('package-lock.json'));
for(const file of ['sshcore/core.go','sshcore/main_js.go','sshcore/go.mod','sshcore/go.sum','android/build.gradle','scripts/build-ssh.mjs'])hash.update(readFileSync(file));
hash.update(readFileSync('android/app/src/main/AndroidManifest.xml'));
hash.update(readFileSync('capacitor.config.ts'));
hash.update(readFileSync('android/app/build.gradle'));
hash.update(readFileSync('ios/App/App.xcodeproj/project.pbxproj'));
const version=JSON.parse(readFileSync('package.json','utf8')).version;
writeFileSync('src/build-info.ts', `// Generated by scripts/build-identity.mjs\nexport const VERSION = ${JSON.stringify(version)};\nexport const BUILD_ID = ${JSON.stringify(hash.digest('hex').slice(0,24))};\n`);
